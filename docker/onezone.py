class Label(IntEnum):
    """
    Label specifiers for pre-releases.
    Ordered by precedence: alpha < beta < rc < stable (no label).
    """

    ALPHA = 1
    BETA = 2
    RC = 3
    STABLE = 4

    @classmethod
    def from_string(cls, s):
        if s == "alpha":
            return cls.ALPHA
        if s == "beta":
            return cls.BETA
        if s == "rc":
            return cls.RC
        raise ValueError(f"Unknown label: {s}")

    def __str__(self) -> str:
        if self == self.ALPHA:
            return "alpha"
        if self == self.BETA:
            return "beta"
        if self == self.RC:
            return "rc"
        return ""


@dataclass
class Revision:
    """
    Represents a system revision based on Calendar Versioning.

    Format: YY.Minor[.Patch][-Label]

    Examples:
        25.0-alpha.1
        25.0
        25.0.1
    """

    year: int
    minor: int
    patch: int = 0
    label: Label = Label.STABLE
    label_ordinal: int = 0

    @property
    def major(self):
        """Compatibility property for old major version (year)."""
        return str(self.year)

    @classmethod
    def parse(cls, revision_str):
        """Parse a revision string into a Revision object."""
        try:
            # Handle empty string or None
            if not revision_str:
                raise ValueError("Empty revision string")

            # Split main part and label
            parts = revision_str.split("-", 1)
            main_part = parts[0]
            label_part = parts[1] if len(parts) > 1 else None

            # Parse numbers
            numbers = [int(n) for n in main_part.split(".")]
            if len(numbers) == 2:
                year, minor = numbers
                patch = 0
            elif len(numbers) == 3:
                year, minor, patch = numbers
            else:
                raise ValueError("Invalid version number format")

            # Parse label
            if label_part is None:
                label = Label.STABLE
                ordinal = 0
            else:
                if year > 21:
                    # Modern format: label.ordinal (e.g., alpha.2)
                    if "." not in label_part:
                        raise ValueError("Invalid modern label format")
                    lbl_str, ord_str = label_part.split(".", 1)
                    label = Label.from_string(lbl_str)
                    ordinal = int(ord_str)
                else:
                    # Legacy format: labelordinal (e.g., alpha2)
                    match = re.match(r"([a-z]+)(\d+)", label_part)
                    if not match:
                        raise ValueError("Invalid legacy label format")
                    lbl_str, ord_str = match.groups()
                    label = Label.from_string(lbl_str)
                    ordinal = int(ord_str)

            return cls(
                year=year, minor=minor, patch=patch, label=label, label_ordinal=ordinal
            )
        except Exception as e:
            raise ValueError(f"Invalid revision format '{revision_str}': {e}") from e

    def get_release_line(self) -> str:
        """Returns concatenated major and minor version, e.g. '21.02' or '25.0'."""
        if self.year <= 21:
            return f"{self.year}.{self.minor:02d}"
        return f"{self.year}.{self.minor}"

    def __str__(self) -> str:
        # Main part
        if self.year <= 21:
            s = f"{self.year}.{self.minor:02d}"
        else:
            s = f"{self.year}.{self.minor}"

        if self.patch > 0 or self.year <= 21:
            s += f".{self.patch}"

        # Label part
        if self.label != Label.STABLE:
            s += "-"
            if self.year > 21:
                s += f"{self.label}.{self.label_ordinal}"
            else:
                s += f"{self.label}{self.label_ordinal}"

        return s

    def __hash__(self):
        return hash(str(self))

    def __repr__(self):
        return f"Revision({str(self)})"

    def _cmp_tuple(self):
        return self.year, self.minor, self.patch, self.label.value, self.label_ordinal

    def __eq__(self, other):
        if not isinstance(other, Revision):
            return NotImplemented
        return self._cmp_tuple() == other._cmp_tuple()

    def __lt__(self, other):
        if not isinstance(other, Revision):
            return NotImplemented
        return self._cmp_tuple() < other._cmp_tuple()

    def __le__(self, other):
        if not isinstance(other, Revision):
            return NotImplemented
        return self._cmp_tuple() <= other._cmp_tuple()

    def __gt__(self, other):
        if not isinstance(other, Revision):
            return NotImplemented
        return self._cmp_tuple() > other._cmp_tuple()

    def __ge__(self, other):
        if not isinstance(other, Revision):
            return NotImplemented
        return self._cmp_tuple() >= other._cmp_tuple()


class MissingVariableError(Exception):
    """Indicates operation error caused by missing environment variable"""
    def __init__(self, variable_name):
        message = "Missing {} environment variable".format(variable_name)
        super(Exception, self).__init__(message)
        self.variable_name = variable_name


class AuthenticationError(Exception):
    """Indicates failure to execute an API request caused by rejected authentication"""
    pass


def log(message, end='\n'):
    sys.stdout.write(message + end)
    sys.stdout.flush()


def replace(file_path, pattern, value):
    with open(file_path, 'r+') as f:
        content = f.read()
        content = re.sub(pattern, value, content)
        f.seek(0)
        f.truncate()
        f.write(content)


def set_node_name(file_path):
    hostname = sp.check_output(['hostname', '-f']).decode().rstrip('\n')
    replace(file_path, r'-name .*', '-name onepanel@{0}'.format(hostname))


def config_file_initialized(file_path):
    try:
        with open(file_path, 'r') as f:
            content = f.read()
            return bool(re.search(r'{config_initialized,\s*true}', content))
    except:
        return False


