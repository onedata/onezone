def infer_new_version():
    """
    Parse RELEASES file and return the onepanel version string (e.g. "25.0").
    Exits with a message if file is missing or version pattern not found.
    """
    releases_path = ONP_RELEASES_PACKAGES_PATH
    if os.environ.get(ONEPANEL_OVERRIDE):
        releases_path = os.path.join(
            os.environ.get(ONEPANEL_OVERRIDE),
            ONP_RELEASES_SOURCES_PATH
        )
    if not os.path.isfile(releases_path):
        log('Could not find RELEASES file at {}'.format(releases_path))
        sys.exit(1)

    try:
        with open(releases_path, 'r') as f:
            content = f.read()
        # e.g. {onepanel,"25.0","./lib/onepanel-25.0"}
        m = re.search(r'\{onepanel\s*,\s*["\']([^"\']+)["\']', content)
        if m:
            return m.group(1).strip()
    except OSError as e:
        log('Failed to read RELEASES file {}: {}'.format(releases_path, e))
        sys.exit(1)

    log('Could not find onepanel version in RELEASES file: {}'.format(releases_path))
    sys.exit(1)


def compare_version(prev_version_str, new_version_str):
    """
    Compare previous (persisted) and new (installed) version using Revision.
    Returns VersionCheckResult: SAME_VERSION, ALLOWED_UPGRADE,
    UPGRADE_JUMP_TOO_BIG, or DOWNGRADE.
    """
    prev_rev = Revision.parse(prev_version_str.strip())
    new_rev = Revision.parse(new_version_str.strip())
    if new_rev < prev_rev:
        return VersionCheckResult.DOWNGRADE
    if new_rev > prev_rev:
        if _major_upgrade_allowed(prev_rev.year, new_rev.year):
            return VersionCheckResult.ALLOWED_UPGRADE
        return VersionCheckResult.UPGRADE_JUMP_TOO_BIG
    return VersionCheckResult.SAME_VERSION


def _major_upgrade_allowed(prev_major, new_major):
    """
    Whether a major-version upgrade is allowed.
    - To 25: both 20 and 21 can go. To 26: from 21 or 25. From 27: step <= 1.
    """
    if new_major <= prev_major:
        return True
    if new_major == 25:
        return prev_major in (20, 21)
    if new_major == 26:
        return prev_major in (21, 25)
    return (new_major - prev_major) <= 1


def parse_major_version(version_str):
    """Extract major version number (year). '20.02.1' -> 20, '25.0' -> 25. (Public for tests/logging.)"""
    return Revision.parse(version_str.strip()).year


def update_persisted_version(previous_version=None):
    """
    Write deployed-version.json. When previous_version is None (fresh deploy),
    only current is written. Otherwise both previous and current are stored.
    """
    current = infer_new_version()
    data = {'current': current}
    if previous_version is not None:
        data['previous'] = previous_version

    os.makedirs(os.path.dirname(ONP_VERSION_FILE_PACKAGES_PATH), exist_ok=True)
    with open(ONP_VERSION_FILE_PACKAGES_PATH, 'w') as f:
        json.dump(data, f, indent=2)


