def assert_upgradability() -> Optional[str]:
    """Check upgradability based on versions.

    Returns previous_version for persistence when not fresh install, None otherwise.
    Exits on disallowed upgrade or downgrade.
    """
    new_version = infer_new_version()

    if not IS_CONFIG_INITIALIZED:
        log(MSG_FRESH_DEPLOYMENT.format(new_version=new_version))
        return None

    prev_version = infer_previous_version()
    result = check_upgradability(prev_version, new_version)

    if result == UpgradabilityCheckResult.DOWNGRADE:
        log(
            MSG_DOWNGRADE.format(prev_version=prev_version, current_version=new_version)
        )
        sys.exit(1)

    elif result == UpgradabilityCheckResult.UPGRADE_JUMP_TOO_BIG:
        log(
            MSG_UPGRADE_JUMP_TOO_BIG.format(
                prev_version=prev_version,
                current_version=new_version,
            )
        )
        sys.exit(1)

    elif result == UpgradabilityCheckResult.SAME_VERSION:
        log(
            MSG_RESUME_SAME_VERSION.format(
                prev_version=prev_version,
                current_version=new_version,
            )
        )

    elif result == UpgradabilityCheckResult.ALLOWED_UPGRADE:
        log(
            MSG_RESUME_UPGRADE.format(
                prev_version=prev_version,
                current_version=new_version,
            )
        )

    return prev_version


def infer_new_version() -> str:
    """Parse RELEASES file and return the onepanel version string (e.g. "25.0").

    Exits with a message if file is missing or version pattern not found.
    """
    if not os.path.isfile(ONP_RELEASES_PATH):
        log(f"Could not find RELEASES file at {ONP_RELEASES_PATH}")
        sys.exit(1)

    try:
        with open(ONP_RELEASES_PATH, "r") as f:
            content = f.read()
        # e.g. {onepanel,"25.0","./lib/onepanel-25.0"}
        m = re.search(r'\{onepanel\s*,\s*["\']([^"\']+)["\']', content)
        if m:
            return m.group(1).strip()
    except OSError as e:
        log(f"Failed to read RELEASES file {ONP_RELEASES_PATH}: {e}")
        sys.exit(1)

    log(f"Could not find onepanel version in RELEASES file: {ONP_RELEASES_PATH}")
    sys.exit(1)


def infer_previous_version():
    try:
        with open(ONP_VERSION_FILE_PACKAGES_PATH, "r") as f:
            data = json.load(f)

        return data["current"]
    except (OSError, ValueError):
        log(MSG_COULD_NOT_RESOLVE_VERSION)
        time.sleep(SLEEP_COULD_NOT_RESOLVE_VERSION_SEC)

        return ONP_DEFAULT_ASSUMED_VERSION


def check_upgradability(
    prev_version_str: str, new_version_str: str
) -> UpgradabilityCheckResult:
    prev_rev = parse_revision(prev_version_str.strip())
    new_rev = parse_revision(new_version_str.strip())

    if new_rev < prev_rev:
        return UpgradabilityCheckResult.DOWNGRADE
    elif new_rev > prev_rev:
        if (new_rev.year - prev_rev.year) <= 1:
            return UpgradabilityCheckResult.ALLOWED_UPGRADE
        elif new_rev.year == 25 and prev_rev.year in (20, 21):
            return UpgradabilityCheckResult.ALLOWED_UPGRADE
        elif new_rev.year == 26 and prev_rev.year in (21, 25):
            return UpgradabilityCheckResult.ALLOWED_UPGRADE

        return UpgradabilityCheckResult.UPGRADE_JUMP_TOO_BIG

    return UpgradabilityCheckResult.SAME_VERSION


def parse_revision(version_str: str) -> Revision:
    try:
        if not version_str:
            raise ValueError("Empty revision string")

        # Split main part and label
        parts = version_str.split("-", 1)
        main_part = parts[0]
        label_part = parts[1] if len(parts) > 1 else None

        # Parse numbers
        numbers = [int(n) for n in main_part.split(".")]
        if len(numbers) == 2:
            year, minor = numbers
            patch = 0
        elif len(numbers) == 3:
            year, minor, patch = numbers
        else:
            raise ValueError("Invalid version number format")

        # Parse label
        if label_part is None:
            label = Label.STABLE
            ordinal = 0
        else:
            if year > 21:
                # Modern format: label.ordinal (e.g., alpha.2)
                if "." not in label_part:
                    raise ValueError("Invalid modern label format")
                lbl_str, ord_str = label_part.split(".", 1)
                label = Label.from_string(lbl_str)
                ordinal = int(ord_str)
            else:
                # Legacy format: labelordinal (e.g., alpha2)
                match = re.match(r"([a-z]+)(\d+)", label_part)
                if not match:
                    raise ValueError("Invalid legacy label format")
                lbl_str, ord_str = match.groups()
                label = Label.from_string(lbl_str)
                ordinal = int(ord_str)

        return Revision(
            year=year, minor=minor, patch=patch, label=label, label_ordinal=ordinal
        )
    except Exception as e:
        raise ValueError(f"Invalid revision format '{version_str}': {e}") from e


def update_persisted_version(previous_version: Optional[str] = None) -> None:
    """Write deployed-version.json.

    When previous_version is None (fresh deploy),only current is written.
    Otherwise, both previous and current are stored.
    """
    current = infer_new_version()
    data: Dict[str, str] = {"current": current}
    if previous_version is not None:
        data["previous"] = previous_version

    os.makedirs(os.path.dirname(ONP_VERSION_FILE_PACKAGES_PATH), exist_ok=True)
    with open(ONP_VERSION_FILE_PACKAGES_PATH, "w") as f:
        json.dump(data, f, indent=4)


