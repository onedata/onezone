def start_onepanel_and_await_readiness() -> None:
    log("Starting oz_panel...")

    cmd = ["service", "oz_panel", "start"]
    if ONEPANEL_OVERRIDE:
        oz_panel_script = os.path.join(ONEPANEL_OVERRIDE, ONP_BIN_SOURCES_PATH)
        cmd = [oz_panel_script, "start"]

    try:
        sp.check_output(cmd)
    except sp.CalledProcessError as err:
        log(f"ERROR: {err}")
        log("Output was:\n")
        log(str(err.output))
        sys.exit(err.returncode)

    wait_for_rest_listener()
    log("[  OK  ] oz_panel started\n")


def wait_for_rest_listener() -> None:
    first = True
    connected = False
    while not connected:
        try:
            requests.get(f"{ONEPANEL_BASE_URL}/api/v3/onepanel/", verify=False)
        except requests.ConnectionError:
            if first:
                log(MSG_WAITING_FOR_PANEL)
                first = False
            time.sleep(1)
        else:
            connected = True


def configure_deployment() -> None:
    batch_config = get_batch_config()
    try:
        if configure(batch_config):
            log(MSG_CONGRATULATIONS)
        else:
            log(MSG_WAITING_FOR_CLUSTER)
            wait_for_workers()
            log(MSG_RESUMED_WORK)
    except AuthenticationError:
        log(MSG_AUTHENTICATION_ERROR)
    except MissingVariableError as e:
        if e.variable_name != EMERGENCY_PASSPHRASE_VARIABLE:
            raise

        if IS_CONFIG_INITIALIZED:
            log(MSG_MISSING_EXISTING_PASSPHRASE)
        else:
            log(MSG_MISSING_NEW_PASSPHRASE)


def get_batch_config():
    batch_config = os.environ.get("ONEZONE_CONFIG", "")
    batch_config = yaml.safe_load(batch_config)
    if not batch_config:
        return {}

    # insert interactiveDeployment mark if not present
    onepanel_config = batch_config.get("onepanel", {})
    if "interactiveDeployment" not in onepanel_config:
        onepanel_config["interactiveDeployment"] = False
        batch_config["onepanel"] = onepanel_config

    return batch_config


def configure(config: dict) -> bool:
    """Attempts to deploy the Onezone.

    Returns False if configuration was skipped because of existing deployment,
    True upon success.
    """
    passphrase = get_emergency_passphrase()

    try:
        set_emergency_passphrase(passphrase)
    except AuthenticationError:
        # emergency passphrase setup failure indicates existing deployment
        return False

    r = auth_request(
        requests.post,
        f"{ONEPANEL_BASE_URL}/api/v3/onepanel/zone/configuration",
        headers={"content-type": "application/x-yaml"},
        data=yaml.dump(config),
        verify=False,
    )

    if r.status_code == codes.conflict:
        return False

    if not r.ok:
        raise RuntimeError(
            f"Failed to start configuration process, the response was:\n"
            f"  code: {r.status_code}\n"
            f"  body: {r.text}\n"
            f"For more information please check the logs."
        )

    poll_configuration_status(r.headers["location"])
    return True


def poll_configuration_status(location: str) -> None:
    """Poll the onepanel task endpoint until configuration completes or fails."""
    status = "running"
    steps: List[str] = []
    resp: dict = {}

    log("\nConfiguring Onezone:")
    while status == "running":
        r = auth_request(requests.get, ONEPANEL_BASE_URL + location, verify=False)
        if not r.ok:
            raise RuntimeError(
                f"Unexpected configuration error\n{r.text}"
                f"For more information please check the logs."
            )

        resp = json.loads(r.text)
        status = resp.get("status", "error")
        for step in resp.get("steps", []):
            if steps and step == steps[0]:
                steps = steps[1:]
            else:
                log(format_step(step))
        steps = resp.get("steps", [])
        time.sleep(1)

    if status != "ok":
        raise RuntimeError(format_error(resp))


def get_emergency_passphrase() -> str:
    passphrase = os.environ.get(EMERGENCY_PASSPHRASE_VARIABLE)
    if passphrase is None:
        raise MissingVariableError(EMERGENCY_PASSPHRASE_VARIABLE)
    return passphrase


def set_emergency_passphrase(passphrase: str) -> None:
    r = requests.put(
        f"{ONEPANEL_BASE_URL}/api/v3/onepanel/emergency_passphrase",
        headers={"content-type": "application/json"},
        data=json.dumps({"newPassphrase": passphrase}),
        verify=False,
    )
    if r.status_code in (codes.unauthorized, codes.forbidden):
        raise AuthenticationError(
            "Could not set Onepanel emergency passphrase due to "
            f"authentication error: {r.status_code} {r.text}"
        )
    if not r.ok:
        raise RuntimeError(
            f"Could not set Onepanel emergency passphrase: {r.status_code} {r.text}"
        )


def auth_request(method: Any, *args: Any, **kwargs: Any) -> requests.Response:
    """Perform an HTTP request with Basic auth using the emergency passphrase."""
    passphrase = get_emergency_passphrase()
    r = method(*args, auth=(PASSPHRASE_USERNAME, passphrase), **kwargs)
    if r.status_code in (codes.unauthorized, codes.forbidden):
        raise AuthenticationError(
            "Authentication error.\n"
            "Please ensure that valid emergency passphrase is present\n"
            f"in the {EMERGENCY_PASSPHRASE_VARIABLE} environment variable"
        )
    return r


